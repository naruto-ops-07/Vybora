-- Explicit grants for the API roles: anon, authenticated, service_role.
--
-- Why: some earlier migrations revoke what a role must not have and rely on
-- Supabase's old default privileges for the rest:
--   alter default privileges in schema public
--     grant all on tables / functions / sequences to anon, authenticated, service_role;
-- Newer hosted Supabase projects don't install those defaults, so anything
-- granted only that way is unreachable there: "Say hi"
-- (rpc('create_secure_conversation')) fails with 42501 for signed-in users,
-- and without the defaults service_role (the Edge Functions' key) holds no
-- privileges on the tables at all.
--
-- What: one grant for every privilege these roles hold on schema public and
-- its tables, views, columns, sequences and functions in the test database
-- (supabase/tests) with the old defaults installed, after these migrations:
--   20261009000001_foundation.sql through 20261016000013_friends.sql (13 files)
-- On a project without the defaults this reproduces that tested state exactly.
-- Nothing the tested state lacks is granted, so the tables and functions the
-- migrations revoked (friend_requests, friendships, user_activity, the
-- service-only maintenance functions...) stay revoked. It contains no revokes.
--
-- Safe to re-run: additive and idempotent. GRANT is a no-op where the
-- privilege is already held, so on a project that still has the old defaults
-- (and in the "defaults" test mode) this changes nothing.
--
-- Generated by scripts/gen-explicit-grants.mjs; don't edit it by hand, and
-- never edit it once applied. supabase/tests/explicit-grants.test.ts runs the
-- whole schema with and without the defaults and fails if they differ. To fix
-- that, add the missing grant to the migration that needs it (if that
-- migration isn't applied anywhere yet), or regenerate into a NEW migration:
--   pnpm db:grants supabase/migrations/<timestamp>_explicit_client_grants.sql

