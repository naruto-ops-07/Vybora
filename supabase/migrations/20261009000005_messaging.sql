-- =====================================================================
-- VYBORA · 0005 · Direct messaging
-- Membership is created only by a trusted function; clients can never
-- insert themselves into a conversation. Messages are visible to members
-- only — moderators/admins have NO read access to message content.
-- =====================================================================

create table public.conversations (
  id               uuid primary key default gen_random_uuid(),
  kind             text not null default 'direct' check (kind in ('direct')),
  direct_key       text unique,
  created_by       uuid references public.profiles (id) on delete set null,
  created_at       timestamptz not null default now(),
  last_message_at  timestamptz not null default now()
);

create table public.conversation_members (
  conversation_id  uuid not null references public.conversations (id) on delete cascade,
  user_id          uuid not null references public.profiles (id) on delete cascade,
  joined_at        timestamptz not null default now(),
  last_read_at     timestamptz not null default now(),
  primary key (conversation_id, user_id)
);

create index conversation_members_user_idx on public.conversation_members (user_id);

create table public.messages (
  id               uuid primary key default gen_random_uuid(),
  conversation_id  uuid not null references public.conversations (id) on delete cascade,
  sender_id        uuid not null default auth.uid() references public.profiles (id) on delete cascade,
  body             text check (body is null or char_length(body) <= 2000),
  attachment_path  text check (attachment_path is null or char_length(attachment_path) <= 300),
  attachment_mime  text check (attachment_mime is null or attachment_mime in ('image/jpeg', 'image/png', 'image/webp', 'image/gif')),
  client_id        uuid,
  created_at       timestamptz not null default now(),
  check (char_length(btrim(coalesce(body, ''))) > 0 or attachment_path is not null),
  check ((attachment_path is null) = (attachment_mime is null)),
  unique (sender_id, client_id)
);

comment on column public.messages.client_id is 'Idempotency key generated by the client so retries never duplicate a message.';

create index messages_conversation_idx on public.messages (conversation_id, created_at desc, id desc);
create index messages_sender_created_idx on public.messages (sender_id, created_at desc);

create or replace function public.is_conversation_member(p_conversation uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.conversation_members m
    where m.conversation_id = p_conversation and m.user_id = auth.uid()
  );
$$;

-- Is the caller blocked with any other member of the conversation?
create or replace function private.conversation_has_block(p_conversation uuid, p_user uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.conversation_members m
    join public.blocks b
      on (b.blocker_id = m.user_id and b.blocked_id = p_user)
      or (b.blocker_id = p_user and b.blocked_id = m.user_id)
    where m.conversation_id = p_conversation and m.user_id <> p_user
  );
$$;

create trigger messages_rate_limit
  before insert on public.messages
  for each row execute function private.enforce_rate_limit('sender_id', '1 minute', '60');

create or replace function private.messages_before_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_meta jsonb;
begin
  new.created_at := now();
  if new.body is not null then
    new.body := btrim(new.body);
    if new.body = '' then
      new.body := null;
    end if;
  end if;
  if private.conversation_has_block(new.conversation_id, new.sender_id) then
    raise exception 'cannot_message' using errcode = 'P0001';
  end if;
  if new.attachment_path is not null then
    if split_part(new.attachment_path, '/', 1) <> new.conversation_id::text
       or split_part(new.attachment_path, '/', 2) <> new.sender_id::text then
      raise exception 'attachment_path_invalid' using errcode = 'P0001';
    end if;
    select o.metadata into v_meta
    from storage.objects o
    where o.bucket_id = 'dm' and o.name = new.attachment_path;
    if not found then
      raise exception 'attachment_not_uploaded' using errcode = 'P0001';
    end if;
    if v_meta ->> 'mimetype' is not null and v_meta ->> 'mimetype' <> new.attachment_mime then
      raise exception 'media_type_mismatch' using errcode = 'P0001';
    end if;
  end if;
  return new;
end;
$$;

create trigger messages_before_insert
  before insert on public.messages
  for each row execute function private.messages_before_insert();

create or replace function private.messages_after_insert()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_member uuid;
  v_preview text := coalesce(left(new.body, 140), 'Sent a photo');
begin
  update public.conversations set last_message_at = new.created_at where id = new.conversation_id;
  update public.conversation_members set last_read_at = new.created_at
    where conversation_id = new.conversation_id and user_id = new.sender_id;

  for v_member in
    select m.user_id from public.conversation_members m
    where m.conversation_id = new.conversation_id and m.user_id <> new.sender_id
  loop
    -- One unread "message" notification per conversation; refreshed on each message.
    update public.notifications
      set created_at = now(), actor_id = new.sender_id, body = v_preview
      where recipient_id = v_member and conversation_id = new.conversation_id
        and type = 'message' and read_at is null;
    if not found then
      perform private.notify(v_member, new.sender_id, 'message', null, null, new.conversation_id, v_preview);
    end if;
  end loop;
  return new;
end;
$$;

create trigger messages_after_insert
  after insert on public.messages
  for each row execute function private.messages_after_insert();

create or replace function private.messages_after_delete()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if old.attachment_path is not null then
    perform private.enqueue_media_deletion('dm', old.attachment_path, 'message_deleted');
  end if;
  return old;
end;
$$;

create trigger messages_after_delete
  after delete on public.messages
  for each row execute function private.messages_after_delete();

alter table public.conversations         enable row level security;
alter table public.conversation_members  enable row level security;
alter table public.messages              enable row level security;

revoke all on public.conversations, public.conversation_members, public.messages from anon, authenticated;

grant select on public.conversations to authenticated;
create policy conversations_select_member on public.conversations
  for select to authenticated using (public.is_conversation_member(id));

grant select, update (last_read_at) on public.conversation_members to authenticated;
create policy members_select on public.conversation_members
  for select to authenticated using (public.is_conversation_member(conversation_id));
create policy members_update_own on public.conversation_members
  for update to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid() and last_read_at <= now() + interval '1 minute');

grant select, insert (conversation_id, sender_id, body, attachment_path, attachment_mime, client_id), delete
  on public.messages to authenticated;
create policy messages_select_member on public.messages
  for select to authenticated using (public.is_conversation_member(conversation_id));
create policy messages_insert_member on public.messages
  for insert to authenticated
  with check (
    sender_id = auth.uid()
    and public.current_user_active()
    and public.is_conversation_member(conversation_id)
  );
-- "Unsend": senders may delete their own messages.
create policy messages_delete_own on public.messages
  for delete to authenticated using (sender_id = auth.uid());

-- ---------------------------------------------------------------------
-- Start (or reuse) a 1:1 conversation. Trusted: creates both memberships.
-- ---------------------------------------------------------------------

create or replace function public.start_direct_conversation(p_other uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
  v_key text;
  v_id uuid;
  v_privacy text;
begin
  if v_me is null then
    raise exception 'not_authenticated' using errcode = 'P0001';
  end if;
  if p_other is null or p_other = v_me then
    raise exception 'invalid_recipient' using errcode = 'P0001';
  end if;
  if not public.current_user_active() then
    raise exception 'account_suspended' using errcode = 'P0001';
  end if;
  if not exists (select 1 from public.profiles p where p.id = p_other and p.status = 'active') then
    raise exception 'profile_unavailable' using errcode = 'P0001';
  end if;
  if exists (
    select 1 from public.blocks b
    where (b.blocker_id = v_me and b.blocked_id = p_other)
       or (b.blocker_id = p_other and b.blocked_id = v_me)
  ) then
    raise exception 'cannot_message' using errcode = 'P0001';
  end if;

  v_key := least(v_me::text, p_other::text) || ':' || greatest(v_me::text, p_other::text);
  select c.id into v_id from public.conversations c where c.direct_key = v_key;
  if v_id is not null then
    return v_id;
  end if;

  select s.message_privacy into v_privacy from public.user_settings s where s.user_id = p_other;
  if v_privacy = 'following' and not exists (
    select 1 from public.follows f
    where f.follower_id = p_other and f.following_id = v_me and f.status = 'accepted'
  ) then
    raise exception 'recipient_restricts_messages' using errcode = 'P0001';
  end if;

  insert into public.conversations (kind, direct_key, created_by)
  values ('direct', v_key, v_me)
  on conflict (direct_key) do nothing
  returning id into v_id;
  if v_id is null then
    select c.id into v_id from public.conversations c where c.direct_key = v_key;
  end if;

  insert into public.conversation_members (conversation_id, user_id)
  values (v_id, v_me), (v_id, p_other)
  on conflict do nothing;

  return v_id;
end;
$$;

revoke execute on function public.start_direct_conversation(uuid) from public, anon;
grant execute on function public.start_direct_conversation(uuid) to authenticated;

-- Inbox: one query (no N+1) with the other participant, last message and unread count.
create or replace function public.my_conversations(
  p_before timestamptz default null,
  p_limit integer default 30
)
returns table (
  conversation_id uuid,
  last_message_at timestamptz,
  other_id uuid,
  other_username text,
  other_display_name text,
  other_avatar_path text,
  last_message_body text,
  last_message_sender uuid,
  last_message_has_attachment boolean,
  unread_count integer
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    c.id,
    c.last_message_at,
    o.id, o.username, o.display_name, o.avatar_path,
    lm.body, lm.sender_id, lm.attachment_path is not null,
    (
      select count(*)::integer from public.messages x
      where x.conversation_id = c.id and x.sender_id <> auth.uid() and x.created_at > me.last_read_at
    )
  from public.conversation_members me
  join public.conversations c on c.id = me.conversation_id
  left join lateral (
    select om.user_id from public.conversation_members om
    where om.conversation_id = c.id and om.user_id <> auth.uid()
    limit 1
  ) other on true
  left join public.profiles o on o.id = other.user_id
  left join lateral (
    select m.body, m.sender_id, m.attachment_path from public.messages m
    where m.conversation_id = c.id
    order by m.created_at desc, m.id desc
    limit 1
  ) lm on true
  where me.user_id = auth.uid()
    and (p_before is null or c.last_message_at < p_before)
  order by c.last_message_at desc
  limit least(greatest(coalesce(p_limit, 30), 1), 100);
$$;

-- Mark a conversation read (and clear its message notification).
create or replace function public.mark_conversation_read(p_conversation uuid)
returns void
language sql
security invoker
set search_path = ''
as $$
  update public.conversation_members set last_read_at = now()
    where conversation_id = p_conversation and user_id = auth.uid();
  update public.notifications set read_at = now()
    where recipient_id = auth.uid() and conversation_id = p_conversation and type = 'message' and read_at is null;
$$;

-- Badge counts for the navigation.
create or replace function public.unread_counts()
returns table (notifications integer, conversations integer)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    (select count(*)::integer from public.notifications n
      where n.recipient_id = auth.uid() and n.read_at is null and n.type <> 'message'),
    (select count(*)::integer from public.conversation_members me
      where me.user_id = auth.uid()
        and exists (
          select 1 from public.messages m
          where m.conversation_id = me.conversation_id
            and m.sender_id <> auth.uid()
            and m.created_at > me.last_read_at
        ));
$$;

create or replace function public.mark_all_notifications_read()
returns void
language sql
security invoker
set search_path = ''
as $$
  update public.notifications set read_at = now()
  where recipient_id = auth.uid() and read_at is null and type <> 'message';
$$;
