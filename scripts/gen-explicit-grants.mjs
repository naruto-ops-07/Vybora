#!/usr/bin/env node
// Writes a migration of explicit GRANTs for the API roles (anon, authenticated,
// service_role). Applied to a database WITHOUT Supabase's old default
// privileges, it reproduces exactly the privileges those roles end up with
// when the migrations run WITH them, which is the state the test suite checks.
//
// It boots the database exactly as supabase/tests does (PGlite, the shim with
// default privileges, every file in supabase/migrations), reads the privileges
// the three roles hold on schema public and its tables, views, columns,
// sequences and functions, and renders one GRANT per object and role group.
//
//   pnpm db:grants supabase/migrations/<timestamp>_explicit_client_grants.sql
//   pnpm db:grants --stdout
//
// It never overwrites a file: a migration that has been applied must not be
// edited, so a new gap is closed by a NEW migration.

import { existsSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';
import { bootDatabase, migrationFiles } from '../supabase/tests/harness/boot.mjs';
import {
  readAllPrivileges,
  readClientPrivileges,
  renderGrantStatements,
} from '../supabase/tests/harness/grants.mjs';

const args = process.argv.slice(2);
const toStdout = args.includes('--stdout');
const out = args.find((a) => !a.startsWith('--'));
if (!toStdout && !out) {
  console.error(
    'Usage: node scripts/gen-explicit-grants.mjs <new-migration.sql> | --stdout\n' +
      'Example: pnpm db:grants supabase/migrations/20261101000015_explicit_client_grants.sql',
  );
  process.exit(2);
}
if (out && existsSync(out)) {
  console.error(
    `${out} already exists. Never edit a migration that may have been applied; ` +
      'write the grants to a new migration file instead.',
  );
  process.exit(1);
}

const pg = await bootDatabase({ mode: 'defaults' });
const statements = renderGrantStatements(
  await readClientPrivileges(pg),
  await readAllPrivileges(pg),
);
await pg.close();

const applied = migrationFiles()
  .map((f) => basename(f))
  .filter((f) => !out || f !== basename(out));

const SECTIONS = {
  schema: 'Schema',
  table: 'Tables: table-level grants, then column-level grants',
  view: 'Views',
  sequence: 'Sequences',
  function: 'Functions (RPCs and helpers used by RLS policies)',
  procedure: 'Procedures',
};

const header = `-- Explicit grants for the API roles: anon, authenticated, service_role.
--
-- Why: some earlier migrations revoke what a role must not have and rely on
-- Supabase's old default privileges for the rest:
--   alter default privileges in schema public
--     grant all on tables / functions / sequences to anon, authenticated, service_role;
-- Newer hosted Supabase projects don't install those defaults, so anything
-- granted only that way is unreachable there: "Say hi"
-- (rpc('create_secure_conversation')) fails with 42501 for signed-in users,
-- and without the defaults service_role (the Edge Functions' key) holds no
-- privileges on the tables at all.
--
-- What: one grant for every privilege these roles hold on schema public and
-- its tables, views, columns, sequences and functions in the test database
-- (supabase/tests) with the old defaults installed, after these migrations:
--   ${applied[0]} through ${applied[applied.length - 1]} (${applied.length} files)
-- On a project without the defaults this reproduces that tested state exactly.
-- Nothing the tested state lacks is granted, so the tables and functions the
-- migrations revoked (friend_requests, friendships, user_activity, the
-- service-only maintenance functions...) stay revoked. It contains no revokes.
--
-- Safe to re-run: additive and idempotent. GRANT is a no-op where the
-- privilege is already held, so on a project that still has the old defaults
-- (and in the "defaults" test mode) this changes nothing.
--
-- Generated by scripts/gen-explicit-grants.mjs; don't edit it by hand, and
-- never edit it once applied. supabase/tests/explicit-grants.test.ts runs the
-- whole schema with and without the defaults and fails if they differ. To fix
-- that, add the missing grant to the migration that needs it (if that
-- migration isn't applied anywhere yet), or regenerate into a NEW migration:
--   pnpm db:grants supabase/migrations/<timestamp>_explicit_client_grants.sql
`;

let body = '';
let section = '';
for (const { kind, sql } of statements) {
  if (kind !== section) {
    section = kind;
    body += `\n-- ${SECTIONS[kind]}\n\n`;
  }
  body += `${sql}\n`;
}
const migration = `${header}${body}`;

if (toStdout) {
  process.stdout.write(migration);
} else if (out) {
  writeFileSync(resolve(out), migration);
  console.log(`Wrote ${statements.length} grant statements to ${out}`);
}
